// Controla aparições guiadas da versão anterior da história.

using UnityEngine;
using UnityEngine.Events;

namespace HorrorGame
{
    public sealed class GhostAppearance : MonoBehaviour
    {
        [Tooltip("Visual child only; no model is generated by this component.")]
        public GameObject visual;
        public Transform player, appearanceAnchor;
        public NarrativeDirector director;
        public string approachedSignal;
        [Min(0)] public float disappearAfter = 0;
        [Min(.1f)] public float approachDistance = 1.8f;
        public UnityEvent onShown = new UnityEvent(), onHidden = new UnityEvent(), onApproached = new UnityEvent();
        bool visible;
        float age;
        public void Show()
        {
            age = 0; visible = true;
            if (appearanceAnchor) transform.SetPositionAndRotation(appearanceAnchor.position, appearanceAnchor.rotation);
            if (visual) visual.SetActive(true);
            onShown.Invoke();
        }
        public void Hide()
        {
            if (!visible) return;
            visible = false; if (visual) visual.SetActive(false); onHidden.Invoke();
        }
        public void RestoreHidden() { visible = false; if (visual) visual.SetActive(false); }
        void Update()
        {
            if (!visible || (director && director.game && director.game.State != GameState.Playing)) return;
            age += Time.deltaTime;
            if (player && Vector3.Distance(player.position, transform.position) <= approachDistance)
            { onApproached.Invoke(); if (director && !string.IsNullOrEmpty(approachedSignal)) director.Signal(approachedSignal); Hide(); }
            else if (disappearAfter > 0 && age >= disappearAfter) Hide();
        }
    }
}
